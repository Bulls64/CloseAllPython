LANGUAGE_NAMES = {"fr": "Français", "en": "English"}


def translate(language, key, **values):
    """Return the string for `key` in `language`, falling back to English."""
    table = TEXT.get(language, TEXT["en"])
    return table.get(key, TEXT["en"][key]).format(**values)


def translate_n(language, key, count, **values):
    """Plural-aware translate: picks `<key>_one` or `<key>_many` (French treats 0 as singular)."""
    singular = count == 1 or (language == "fr" and count == 0)
    return translate(language, f"{key}_{'one' if singular else 'many'}", count=count, **values)


def format_seconds(language, value):
    """1.2 -> '1.2' in English, '1,2' in French."""
    text = f"{value:.1f}".rstrip("0").rstrip(".")
    return text.replace(".", ",") if language == "fr" else text
